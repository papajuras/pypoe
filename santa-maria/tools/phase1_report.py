def render_examples(r, n=5, maxlen=1400):
    ex = r['examples']
    if not ex:
        return '_no records_'
    parts = []
    for rec in ex[:n]:
        s = rec['record']
        if len(s) > maxlen:
            s = s[:maxlen] + '\n…[truncated]'
        if 'key' in rec:
            parts.append(f"`{em(rec['key'])}` →\n```json\n{s}\n```")
        else:
            parts.append(f"```json\n{s}\n```")
    return '\n\n'.join(parts)


def render_crossrefs(r):
    c = r.get('crossrefs') or {}
    if not c:
        return ''
    lines = []
    for cls in sorted(c):
        v = c[cls]
        desc = REF_CLASSES.get(cls) or KEY_CLASSES.get(cls) or ('', '')
        lines.append(f"- **{cls}** ({desc[0]}): {fmt_int(v['field_occurrences'])} field "
                     f"occurrences in {fmt_int(v['records_touched'])} records; "
                     f"{fmt_int(v['distinct_count'])} distinct values"
                     + (' (int candidates incl. numeric ids/hashes)' if cls in ('trade_hash', 'numeric_id') else ''))
        if v['sample']:
            ex = '; '.join(f"`{em(x[2])[:70]}`" for x in v['sample'][:3])
            lines.append(f"  - sample: {ex}")
        for p, pn in sorted(v['paths'].items()):
            lines.append(f"  - at `{em(p)}`: {fmt_int(pn['occurrences'])} occ, "
                         f"{fmt_int(pn['distinct_count'])} distinct")
    return '\n'.join(lines)


def render_conversion(r):
    c = r.get('conversion') or {}
    if not c:
        return ''
    lines = []
    for pat in SCAN_PATTERNS:
        v = c.get(pat)
        if not v:
            continue
        lines.append(f"- `{pat}`: {fmt_int(v['field_occurrences'])} field occurrences / "
                     f"{fmt_int(v['record_occurrences'])} records / {fmt_int(v['unique_count'])} distinct values")
        if v['sample']:
            ex = '; '.join(f"`{em(x[2])[:60]}`" for x in v['sample'][:3])
            lines.append(f"  - sample: {ex}")
        ctx = v.get('contexts') or {}
        if ctx:
            notes = []
            for path in sorted(ctx)[:4]:
                for kind, kc in ctx[path].items():
                    notes.append(f"`{em(path)}`[{kind}] ×{fmt_int(kc['occurrences'])} "
                                 f"({fmt_int(kc['distinct_count'])} distinct)")
            if notes:
                lines.append("  - contexts (path[kind] ×occ, distinct): " + '; '.join(notes))
            if len(ctx) > 4:
                lines.append(f"  - …and {len(ctx) - 4} more contexts (full list in `cache/analysis.json`)")
    return '\n'.join(lines)



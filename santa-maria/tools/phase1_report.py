def em(s):
    return str(s).replace('`', '\\`')


def fmt_int(n):
    return f"{n:,}"


# --------------------------------------------------------------------------
# schema rendering
# --------------------------------------------------------------------------

def _children(paths, parent):
    pref = f'{parent}.'
    return sorted(p for p in paths if p.startswith(pref) and p[len(pref):].count('.') == 0
                  and not p[len(pref):].endswith('[]'))


def _parent_present(schema, path, record_count):
    if '.' not in path:
        return record_count
    seg = path.rsplit('.', 1)[0]
    node = schema.get(seg)
    return node['present_in'] if node and 'present_in' in node else record_count


def _sample_str(sample):
    if not sample:
        return ''
    parts = []
    for s in sample:
        if s is None:
            parts.append('`null`')
        else:
            parts.append(f'`{em(s if isinstance(s, str) else s)[:60]}`')
    return ' e.g. ' + ', '.join(parts[:3])


def render_schema(schema, record_count):
    """Exhaustive schema -> markdown. Stat-id-keyed leaf maps (e.g. a
    passive's stats{stat_id}) are compacted to one line; counts stay exact."""
    paths = set(schema)
    # dict paths with >= STAT_COMPACT_MIN children that are predominantly
    # stat-id leaves (a passive's stats{stat_id}, gem stat_text{stat_id}) are
    # compacted to one line; counts stay exact. Fixed field-dicts whose names
    # happen to be stat ids (e.g. a per_level entry's ~12 fields) are below
    # the threshold and stay fully listed.
    STAT_COMPACT_MIN = 30
    stat_maps = set()
    for p in list(paths):
        node = schema.get(p)
        if not node or node['key_union'] is None:
            continue
        kids = _children(paths, p)
        if len(kids) < STAT_COMPACT_MIN:
            continue
        stat_kids = [k for k in kids if k.rsplit('.', 1)[1] in VOCAB]
        if stat_kids and len(stat_kids) >= 0.6 * len(kids):
            stat_maps.add(p)
    lines = []
    for p in sorted(paths):
        node = schema[p]
        denom = _parent_present(schema, p, record_count)
        if p.endswith('.{}'):
            present = f"present in {fmt_int(node['present_in'])} instances"
        else:
            present = f"present in {fmt_int(node['present_in'])}/{fmt_int(denom)}"
        arr = f"; array elements: {','.join(node['arr_elem_types'])}" if node['arr_elem_types'] else ''
        if p in stat_maps:
            kids = _children(paths, p)
            stat_kids = sorted(k.rsplit('.', 1)[1] for k in kids if k.rsplit('.', 1)[1] in VOCAB)
            lines.append(f"- `{em(p)}{{}}` — object keyed by stat id, **{len(stat_kids)} distinct keys** "
                         f"(merged; {present}); sample stat ids: "
                         f"{', '.join('`' + em(x) + '`' for x in stat_kids[:5])}")
            continue
        if '.' in p and p.rsplit('.', 1)[0] in stat_maps:
            continue  # covered by the compacted parent line
        extra = ''
        if node['key_union'] is not None:
            if p + '.{}' in paths and node['key_union'] > 2:
                ks = node.get('key_sample') or []
                ks_note = f"; key_sample (first {len(ks)} of {node['key_union']}, not a complete list — full key list in machine cache `keyed_maps`): " \
                          f"{', '.join('`' + em(x) + '`' for x in ks[:5])}" if ks else ''
                extra = f" — keyed map, **{node['key_union']} distinct keys**{ks_note}"
            elif node['key_union'] > 2:
                extra = f" — {node['key_union']} direct keys"
        s = _sample_str(node['sample'])
        label = em(p) if p else '(record root)'
        lines.append(f"- `{label}`: {','.join(node['types'])}{arr}{extra} | {present}{s}")
    if not lines:
        return '_no fields (records are scalars — see Examples)_'
    return '\n'.join(lines)



def jsonschema_discrepancy(relpath, schema):
    """Compare observed top-level field names against a provided data-formats
    JSON-Schema. Lightweight: top-level properties only."""
    base = os.path.basename(relpath)
    fmt_path = ROOT / 'repoe/data-formats' / base
    if not fmt_path.exists():
        return None
    try:
        doc = json.load(open(fmt_path))
    except Exception:
        return None
    props = set()
    ap = doc.get('additionalProperties')
    target = doc
    ref = ap.get('$ref') if isinstance(ap, dict) else None
    if isinstance(ref, str) and ref.startswith('#/definitions/'):
        target = doc.get('definitions', {}).get(ref.split('/')[-1], doc)
    props = set((target.get('properties') or {}).keys())
    observed = set(p for p in schema
                   if '.' not in p and '[]' not in p and p != '')
    in_schema_not_observed = sorted(props - observed)
    observed_not_in_schema = sorted(observed - props)
    note = f"Provided JSON-Schema `data-formats/{base}`: {len(props)} top-level fields."
    if in_schema_not_observed:
        note += f" **Not observed in the actual export:** {', '.join('`' + em(x) + '`' for x in in_schema_not_observed[:10])}"
    if observed_not_in_schema:
        note += f" Observed but not in the JSON-Schema: {', '.join('`' + em(x) + '`' for x in observed_not_in_schema[:10])}"
    return note


def dataset_section(r, vocab=VOCAB, note=None):
    global SECTIONS
    SECTIONS += 1
    p = PURPOSES.get(r['relpath']) or purpose_line(r['relpath'])
    OUT.append(f"\n### `{r['relpath']}`")
    OUT.append(f"**Purpose**: {p or '—'}")
    if not r.get('parse_ok'):
        OUT.append(f"**ERROR — file did not parse**: {r['error']} (size {r['size']} bytes)")
        return
    OUT.append(f"**Records**: `{r['record_count']}` | **Size**: {round(r['size'] / 1024, 1)} KB | "
               f"**Shape**: `{r['shape']}` | **Max nesting depth**: {r['max_nesting_depth']}")
    OUT.append(f"**Record-count semantics**: {r['record_count_semantics']}.")
    if r['records_scanned'] != r['record_count']:
        OUT.append(f"**WARNING**: scanned {r['records_scanned']} != record_count {r['record_count']}.")
    if note:
        OUT.append(f"**{note}**")
    OUT.append("\n**Field schema** (derived from the **exhaustive scan** of **100%** of records — every "
               "record, field, array element and nesting level; shown STRUCTURALLY COMPACTED: keyed maps "
               "render as `{}` with the exact `key_union` distinct-key count. The machine-readable cache "
               "(`analysis.json` → `keyed_maps`) holds the complete observed key/schema inventory for every "
               "keyed map — full concrete key list, value types, per-shape child schemas — so no schema "
               "information is lost by this compact view):")
    OUT.append(render_schema(r['schema'], r['record_count']))
    disc = jsonschema_discrepancy(r['relpath'], r['schema'])
    if disc:
        OUT.append(f"\n{disc}")
    OUT.append("\n**Examples** (serialized from parsed JSON and truncated to ~1,400 chars per record — "
               "NOT verbatim; the raw files in `data/` are authoritative. First 5 records only — sampled, "
               "not exhaustive):")
    OUT.append(render_examples(r))
    cb = render_crossrefs(r)
    if cb:
        OUT.append("\n**Cross-reference findings** (scanned across **100%** of records/fields/string+int "
                   "values; candidates vs resolved kept separate; counts exhaustive, samples capped for "
                   "readability):")
        OUT.append(cb)
    cv = render_conversion(r)
    if cv:
        OUT.append("\n**Conversion / scaling-indicator findings** (scanned across **100%** of keys and "
                   "string values; counts exhaustive, samples capped; full stat-id context in "
                   "`cache/stat_conversion_context.json`):")
        OUT.append(cv)


